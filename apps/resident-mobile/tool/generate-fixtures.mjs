// Embeds the pinned fixture corpus as a Dart asset so the shell runs on a device
// without a network client.
//
// A NODE PORT of generate_fixtures.dart (GEN-056): generation needs no Flutter.
// The contract test compares jsonDecode(embedded) with jsonDecode(source), so the
// embedding is SEMANTIC — node's JSON.stringify and Dart's jsonEncode both round-trip
// the same object, and an edited fixture still fails the build.
//
// Run:  node tool/generate-fixtures.mjs   (from apps/resident-mobile)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const corpus = '../../tests/fixtures/resident-mobile';

if (!existsSync(`${corpus}/index.json`)) {
  console.error(`Fixture corpus not found at ${corpus}`);
  process.exit(1);
}
const manifest = JSON.parse(readFileSync(`${corpus}/index.json`, 'utf8'));
const entries = manifest.fixtures;

const lines = [];
const w = (s = '') => lines.push(s);

w('// GENERATED by tool/generate-fixtures.mjs. Do not edit by hand.');
w('// Source: tests/fixtures/resident-mobile/index.json');
w(`// Contract version: ${manifest.contractVersion}`);
w('library;');
w();
w('abstract final class FixtureCorpus {');
w(`  static const contractVersion = '${manifest.contractVersion}';`);
w();
w('  /// screen -> state -> raw JSON. Entries with no server response');
w('  /// (loading, offline, duplicate-submission) are absent by design.');
w('  static const Map<String, Map<String, String>> byScreenAndState = {');

const byScreen = new Map();
for (const e of entries) {
  if (!byScreen.has(e.screen)) byScreen.set(e.screen, []);
  byScreen.get(e.screen).push(e);
}
let embedded = 0;
for (const [screen, es] of byScreen) {
  w(`    '${screen}': {`);
  for (const e of es) {
    if (e.file == null) continue;
    const raw = readFileSync(`${corpus}/${e.file}`, 'utf8');
    const compact = JSON.stringify(JSON.parse(raw));
    w(`      '${e.state}': r'''${compact}''',`);
    embedded++;
  }
  w('    },');
}
w('  };');
w();
w('  /// The KIND of each corpus group, DERIVED (GEN-056): a group is a SCREEN iff it has');
w('  /// a data-fetch fixture — a GET operation returning 200 — which is what makes it a');
w('  /// screen with a state matrix. Everything else (Problem bodies, act responses) shares');
w('  /// the corpus but is not a screen. Derived from the contract fields (operationId +');
w('  /// httpStatus), never a hand-kept list of screen names.');
w('  static const Map<String, String> screenKind = {');
for (const [screen, es] of byScreen) {
  const fetches = es.some((e) => /^get/i.test(String(e.operationId ?? '')) && e.httpStatus === 200);
  w(`    '${screen}': '${fetches ? 'screen' : 'operation-fixture'}',`);
}
w('  };');
w();
w('  /// States that legitimately have no server payload, keyed');
w("  /// 'screen/state', with the reason the contract gives.");
w('  static const Map<String, String> clientOnlyReasons = {');
for (const e of entries.filter((e) => e.clientOnly === true)) {
  const reason = e.reason.replaceAll("'", "\\'");
  w(`    '${e.screen}/${e.state}': '${reason}',`);
}
w('  };');
w('}');

writeFileSync('lib/data/fixture_corpus.g.dart', lines.join('\n') + '\n');
console.log(`Embedded ${embedded} fixtures across ${byScreen.size} screens (contract ${manifest.contractVersion})`);
