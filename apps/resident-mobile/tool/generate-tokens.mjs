// Generates lib/theme/severity_tokens.g.dart from the pinned contract.
//
// A NODE PORT of generate_tokens.dart (GEN-056): generation lives where every
// other generator lives and needs no Flutter to run. The output is byte-for-byte
// the Dart generator's, so a Flutter test re-reading severity.json still asserts
// equality and drift still fails the build.
//
// Run:  node tool/generate-tokens.mjs   (from apps/resident-mobile)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const contractPath = '../../packages/api-contracts/resident-mobile/severity.json';

const dartColor = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;

if (!existsSync(contractPath)) {
  console.error(`Contract not found at ${contractPath}`);
  process.exit(1);
}
const contract = JSON.parse(readFileSync(contractPath, 'utf8'));
const version = contract.contractVersion;
const order = contract.levelOrder;
const levels = contract.levels;

const lines = [];
const w = (s = '') => lines.push(s);

w('// GENERATED by tool/generate-tokens.mjs. Do not edit by hand.');
w('// Source: packages/api-contracts/resident-mobile/severity.json');
w(`// Contract version: ${version}`);
w("import 'package:flutter/painting.dart';");
w();
w('/// The canonical severity enumeration. Seven levels, not six:');
w('/// offline ("the service is not reporting") and unknown ("we cannot');
w('/// determine the condition") are different statements to a resident.');
w('enum Severity {');
for (const k of order) w(`  ${k}('${k}'),`);
w('  ;');
w();
w('  const Severity(this.wireValue);');
w('  final String wireValue;');
w();
w('  static Severity fromWire(String v) => values.firstWhere(');
w('        (e) => e.wireValue == v,');
w("        orElse: () => throw ArgumentError('Unknown severity: \$v'),");
w('      );');
w('}');
w();
w('class SeverityTokenSet {');
w('  const SeverityTokenSet({');
w('    required this.strong,');
w('    required this.surface,');
w('    required this.border,');
w('    required this.icon,');
w('    required this.labelEn,');
w('    required this.labelZhHant,');
w('  });');
w('  final Color strong;');
w('  final Color surface;');
w('  final Color border;');
w('  final String icon;');
w('  final String labelEn;');
w('  final String labelZhHant;');
w('}');
w();
w('abstract final class SeverityTokens {');
w(`  static const contractVersion = '${version}';`);
w();
w('  static const Map<Severity, SeverityTokenSet> byLevel = {');
for (const k of order) {
  const lv = levels[k];
  const c = lv.color;
  const label = lv.label;
  w(`    Severity.${k}: SeverityTokenSet(`);
  w(`      strong: Color(${dartColor(c.strong)}),`);
  w(`      surface: Color(${dartColor(c.surface)}),`);
  w(`      border: Color(${dartColor(c.border)}),`);
  w(`      icon: '${lv.icon}',`);
  w(`      labelEn: '${label.en}',`);
  w(`      labelZhHant: '${label['zh-Hant']}',`);
  w('    ),');
}
w('  };');
w();
w('  static SeverityTokenSet of(Severity s) => byLevel[s]!;');
w('}');

writeFileSync('lib/theme/severity_tokens.g.dart', lines.join('\n') + '\n');
console.log(`Generated lib/theme/severity_tokens.g.dart from contract ${version} (${order.length} levels)`);
