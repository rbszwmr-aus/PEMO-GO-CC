const MAP: ReadonlyMap<string, string> = (() => {
  const from = [...FROM];
  const to = [...TO];
  return new Map(from.map((c, i) => [c, to[i]!] as const));
})();

const memo = new Map<string, string>();

/** The Simplified spelling of a Traditional string. Text with no Han character comes back as it is. */
export function toHans(text: string): string {
  const hit = memo.get(text);
  if (hit !== undefined) return hit;
  let out = '';
  for (const c of text) out += MAP.get(c) ?? c;
  if (memo.size > 5000) memo.clear();
  memo.set(text, out);
  return out;
}

