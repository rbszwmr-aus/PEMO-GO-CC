/**
 * Generates design tokens. Never transcribes them.
 *
 * Severity comes from packages/api-contracts/resident-mobile/severity.json,
 * which is normative for both surfaces. The non-severity palette comes from
 * tokens/palette.json, which is DATA and is parity-checked against the resident
 * surface — see that file's `theRuleThisEncodes`.
 *
 * Output is committed and regenerate-and-compare tested, so a stale generated
 * file fails the build rather than shipping.
 *
 * Mirrors apps/resident-mobile/tool/generate_tokens.dart, deliberately.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_ROOT, readSeverityJson } from './corpus-source.ts';

const BANNER = (source: string) =>
  `// GENERATED FILE — DO NOT EDIT.\n` +
  `// Generated by apps/management-web/tool/generate-tokens.ts from ${source}.\n` +
  `// Run \`pnpm run generate\`. A stale copy fails test/tokens/*.test.ts.\n`;

const CSS_BANNER = (source: string) =>
  `/* GENERATED FILE — DO NOT EDIT.\n` +
  ` * Generated by apps/management-web/tool/generate-tokens.ts from ${source}.\n` +
  ` * Run \`pnpm run generate\`. A stale copy fails test/tokens/*.test.ts. */\n`;

const cssVar = (name: string) => `--pemo-${name.replace(/\./g, '-')}`;

export function buildSeverityTs(severity: any): string {
  const order: string[] = severity.levelOrder;
  const lines: string[] = [];

  lines.push(BANNER('packages/api-contracts/resident-mobile/severity.json'));
  lines.push(`//`);
  lines.push(`// SEVEN levels. The design export defines six and has no \`offline\`;`);
  lines.push(`// ADR-007 D7 gives structural authority to the ADRs and UI-010-ST settled`);
  lines.push(`// seven against a ruling that could have reduced it. Read, never transcribed.`);
  lines.push(``);
  lines.push(`export const SEVERITY_CONTRACT_VERSION = ${JSON.stringify(severity.contractVersion)};`);
  lines.push(``);
  lines.push(`export const SEVERITY_ORDER = [`);
  for (const l of order) lines.push(`  ${JSON.stringify(l)},`);
  lines.push(`] as const;`);
  lines.push(``);
  lines.push(`export type SeverityLevel = (typeof SEVERITY_ORDER)[number];`);
  lines.push(``);
  lines.push(`export interface SeverityToken {`);
  lines.push(`  readonly value: SeverityLevel;`);
  lines.push(`  readonly label: { readonly en: string; readonly 'zh-Hant': string };`);
  lines.push(`  readonly color: { readonly strong: string; readonly surface: string; readonly border: string };`);
  lines.push(`  readonly icon: string;`);
  lines.push(`  readonly meaning: string;`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`export const SEVERITY: { readonly [K in SeverityLevel]: SeverityToken } = {`);
  for (const l of order) {
    const t = severity.levels[l];
    lines.push(`  ${JSON.stringify(l)}: {`);
    lines.push(`    value: ${JSON.stringify(t.value)},`);
    lines.push(`    label: { en: ${JSON.stringify(t.label.en)}, 'zh-Hant': ${JSON.stringify(t.label['zh-Hant'])} },`);
    lines.push(
      `    color: { strong: ${JSON.stringify(t.color.strong)}, surface: ${JSON.stringify(t.color.surface)}, border: ${JSON.stringify(t.color.border)} },`,
    );
    lines.push(`    icon: ${JSON.stringify(t.icon)},`);
    lines.push(`    meaning: ${JSON.stringify(t.meaning)},`);
    lines.push(`  },`);
  }
  lines.push(`} as const;`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * Client connectivity is NEVER a severity — severity.json notASeverity.`);
  lines.push(` * The server cannot know the client's network state, so it can never emit one.`);
  lines.push(` */`);
  lines.push(`export const CLIENT_CONNECTIVITY_IS_NOT_A_SEVERITY = true;`);
  lines.push(``);
  return lines.join('\n');
}

export function buildSeverityCss(severity: any): string {
  const order: string[] = severity.levelOrder;
  const lines: string[] = [CSS_BANNER('packages/api-contracts/resident-mobile/severity.json'), ``, `:root {`];
  for (const l of order) {
    const c = severity.levels[l].color;
    lines.push(`  ${cssVar(`sev-${l}-strong`)}: ${c.strong};`);
    lines.push(`  ${cssVar(`sev-${l}-surface`)}: ${c.surface};`);
    lines.push(`  ${cssVar(`sev-${l}-border`)}: ${c.border};`);
  }
  lines.push(`}`);
  lines.push(``);
  return lines.join('\n');
}

export function buildPaletteTs(palette: any): string {
  const lines: string[] = [];
  lines.push(BANNER('apps/management-web/tokens/palette.json'));
  lines.push(`//`);
  lines.push(`// Non-severity palette. Parity-checked against`);
  lines.push(`// apps/resident-mobile/lib/theme/pemo_colors.dart by`);
  lines.push(`// test/tokens/palette-parity.test.ts, in BOTH directions.`);
  lines.push(``);
  lines.push(`export const PALETTE = {`);
  for (const [name, def] of Object.entries<any>(palette.shared)) {
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(def.value)},`);
  }
  for (const [name, def] of Object.entries<any>(palette.managementOnly)) {
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(def.value)},`);
  }
  lines.push(`} as const;`);
  lines.push(``);
  lines.push(`export type PaletteToken = keyof typeof PALETTE;`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * accent.heading measures 3.13:1 on white — LARGE TEXT AA ONLY.`);
  lines.push(` * Design system v2.0 section 2.5 requires it be reachable only as a single`);
  lines.push(` * constrained page-title style, never as a raw colour, because a colour that`);
  lines.push(` * passes only at large sizes otherwise migrates into a caption within weeks.`);
  lines.push(` */`);
  lines.push(`export const PAGE_TITLE_ONLY_TOKENS = ['accent.heading'] as const;`);
  lines.push(``);
  return lines.join('\n');
}

export function buildPaletteCss(palette: any): string {
  const lines: string[] = [CSS_BANNER('apps/management-web/tokens/palette.json'), ``, `:root {`];
  for (const [name, def] of Object.entries<any>(palette.shared)) {
    lines.push(`  ${cssVar(name)}: ${def.value};`);
  }
  for (const [name, def] of Object.entries<any>(palette.managementOnly)) {
    lines.push(`  ${cssVar(name)}: ${def.value};`);
  }
  for (const [name, value] of Object.entries<any>(palette.nonColorSurfaces)) {
    if (name.startsWith('$')) continue;
    lines.push(`  ${cssVar(name)}: ${value};`);
  }
  lines.push(`}`);
  lines.push(``);
  return lines.join('\n');
}

export function readPaletteJson(): any {
  return JSON.parse(readFileSync(join(APP_ROOT, 'tokens/palette.json'), 'utf8'));
}

export function generateAll(): Record<string, string> {
  const severity = readSeverityJson();
  const palette = readPaletteJson();
  return {
    'src/theme/severity-tokens.g.ts': buildSeverityTs(severity),
    'src/theme/severity-tokens.g.css': buildSeverityCss(severity),
    'src/theme/palette.g.ts': buildPaletteTs(palette),
    'src/theme/palette.g.css': buildPaletteCss(palette),
  };
}

const isMain =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  for (const [rel, body] of Object.entries(generateAll())) {
    writeFileSync(join(APP_ROOT, rel), body, 'utf8');
    console.log(`generated ${rel} (${body.split('\n').length} lines)`);
  }
}
