/**
 * Generates src/theme/style-4s.g.css from tokens/style-4s.json.
 *
 * The 4S Web UI Style Guide (4S-DS-WEB-001 v1.1) is DATA here, never source:
 * no hex literal appears in any hand-written file (test/tokens/no-hardcoded-hex).
 * The legacy --pemo-* custom properties that every component already reads are
 * re-pointed at the --s4-* tokens, so the whole app re-skins from this one file.
 * palette.json and severity.json are NOT edited (they are parity-checked
 * against the Flutter app); this layer loads after them and wins.
 *
 * Output is committed and regenerate-and-compare tested (test/tokens/style-4s).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const APP_NAME = APP_ROOT.split('/').pop();

const kebab = (s: string) =>
  s.replace(/([a-z])([A-Z]+)/g, '$1-$2').replace(/([a-z])(\d)/g, '$1-$2').toLowerCase();

export function readStyle4s(): any {
  return JSON.parse(readFileSync(join(APP_ROOT, 'tokens/style-4s.json'), 'utf8'));
}

/** Every token the guide defines, as [css custom property, value]. */
export function s4Variables(j: any): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  for (const [k, v] of Object.entries<string>(j.colour)) out.push([`--s4-${kebab(k)}`, v]);
  for (const [k, v] of Object.entries<{ fg: string; bg: string }>(j.tags)) {
    out.push([`--s4-tag-${kebab(k)}-fg`, v.fg], [`--s4-tag-${kebab(k)}-bg`, v.bg]);
  }
  for (const [k, v] of Object.entries<string>(j.sidebar)) out.push([`--s4-sidebar-${kebab(k)}`, v]);
  for (const [k, v] of Object.entries<string>(j.ref ?? {})) out.push([`--ref-${kebab(k)}`, v]);
  out.push(['--s4-font-sans', j.ref?.fontSans ?? j.type.fontSans]);
  for (const [k, v] of Object.entries<{ size: string; weight: string }>(j.type)) {
    if (typeof v === 'string') continue;
    // Sizes carry the profile text scale (guide section 3): Standard 1, Large 1.2, Extra large 1.4.
    out.push([`--s4-${kebab(k)}-size`, `calc(${v.size} * var(--text-scale, 1))`], [`--s4-${kebab(k)}-weight`, v.weight]);
  }
  for (const [k, v] of Object.entries<string>(j.radius)) out.push([`--s4-radius-${kebab(k)}`, v]);
  return out;
}

export function buildStyle4sCss(j: any): string {
  const vars = s4Variables(j);
  const defined = new Set(vars.map(([n]) => n));
  const lines: string[] = [
    `/* GENERATED FILE — DO NOT EDIT.`,
    ` * Generated by apps/${APP_NAME}/tool/generate-style-4s.ts from apps/${APP_NAME}/tokens/style-4s.json`,
    ` * (${j.guide}). Run \`pnpm run generate\`. A stale copy fails test/tokens/style-4s.test.ts. */`,
    ``,
    `:root {`,
    `  --text-scale: 1;`,
  ];
  for (const [n, v] of vars) lines.push(`  ${n}: ${v};`);
  lines.push(`  /* Legacy --pemo-* properties, re-pointed at the 4S tokens. */`);
  for (const [n, ref] of Object.entries<string>(j.aliases)) {
    const m = /^var\((--s4-[a-z0-9-]+)\)$/.exec(ref);
    if (!m || !defined.has(m[1]!)) throw new Error(`alias ${n} points at an unknown token: ${ref}`);
    lines.push(`  ${n}: ${ref};`);
  }
  lines.push(`}`);
  lines.push(`:root[data-text-size="large"] { --text-scale: 1.2; }`);
  lines.push(`:root[data-text-size="xlarge"] { --text-scale: 1.4; }`);
  lines.push(``);
  return lines.join('\n');
}

export function generateStyle4s(): Record<string, string> {
  return { 'src/theme/style-4s.g.css': buildStyle4sCss(readStyle4s()) };
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  for (const [rel, body] of Object.entries(generateStyle4s())) {
    writeFileSync(join(APP_ROOT, rel), body, 'utf8');
    console.log(`generated ${rel} (${body.split('\n').length} lines)`);
  }
}
