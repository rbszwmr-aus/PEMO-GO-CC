/**
 * THE REASON-CODE VOCABULARY, DERIVED (UI-054 D2, closing UI-051 G3).
 *
 * `packages/api-contracts/notice-reasons.json` is THE ONE SOURCE (GEN-052 D3): the
 * server registry is generated from it and the contract's
 * `NoticeTransitionRequest.reasonCode` enum is verified against its union. This
 * generator writes the client's copy — per-act subsets keyed by the contract's
 * operationId, plus the union as a type — so a select can offer exactly what the
 * act accepts, and a code outside the union is a TYPE ERROR rather than a runtime
 * refusal. A hand-kept subset would go stale the day a code is added; this file is
 * regenerated by `pnpm run generate` and a stale copy reds
 * test/guard/notice-reasons.test.ts.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_ROOT, REPO_ROOT } from './corpus-source.ts';

export const REGISTRY_PATH = join(REPO_ROOT, 'packages/api-contracts/notice-reasons.json');
export const OUTPUT_REL = 'src/data/notice-reasons.g.ts';

interface Registry {
  acts: Record<string, { required: boolean; codes: string[] }>;
}

/** `approve_notice` → `approveNotice`: the registry keys by act name, the client by operationId. */
export const operationIdOf = (act: string): string =>
  act.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());

export function buildNoticeReasonsTs(): string {
  const reg = JSON.parse(readFileSync(REGISTRY_PATH, 'utf8')) as Registry;
  const acts = Object.keys(reg.acts).sort();
  const union = [...new Set(acts.flatMap((a) => reg.acts[a]!.codes))].sort();
  const lines: string[] = [];
  lines.push(`// GENERATED FILE — DO NOT EDIT.`);
  lines.push(`// Generated by apps/management-web/tool/generate-notice-reasons.ts from`);
  lines.push(`// packages/api-contracts/notice-reasons.json, which is READ-ONLY to this app.`);
  lines.push(`// Run \`pnpm run generate\`. A stale copy fails test/guard/notice-reasons.test.ts.`);
  lines.push(``);
  lines.push(`/** Every reasonCode any notice transition accepts — the contract's enum. */`);
  lines.push(`export const NOTICE_REASON_CODES = [`);
  for (const c of union) lines.push(`  ${JSON.stringify(c)},`);
  lines.push(`] as const;`);
  lines.push(`export type NoticeReasonCode = (typeof NOTICE_REASON_CODES)[number];`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * Per-act subsets, keyed by the contract's operationId. An act absent here takes`);
  lines.push(` * no reason code at all; \`required\` is the act's rule, not the client's.`);
  lines.push(` */`);
  lines.push(`export const NOTICE_REASONS: Readonly<Record<string, { readonly required: boolean; readonly codes: readonly NoticeReasonCode[] }>> = {`);
  for (const a of acts) {
    const { required, codes } = reg.acts[a]!;
    lines.push(`  ${JSON.stringify(operationIdOf(a))}: { required: ${required}, codes: [${codes.map((c) => JSON.stringify(c)).join(', ')}] },`);
  }
  lines.push(`};`);
  lines.push(``);
  return lines.join('\n');
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const body = buildNoticeReasonsTs();
  writeFileSync(join(APP_ROOT, OUTPUT_REL), body, 'utf8');
  console.log(`generated ${OUTPUT_REL} (${body.split('\n').length} lines)`);
}
