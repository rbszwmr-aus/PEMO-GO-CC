/**
 * Embeds the fixture corpus into a generated TypeScript module for the browser.
 *
 * The browser cannot read tests/fixtures/**, and this app has no network client
 * — it is fixture-backed by rule, and there is no live backend to build against.
 * So the corpus is generated in, exactly as UI-007-ST generated
 * apps/resident-mobile/lib/data/fixture_corpus.g.dart.
 *
 * The guard in corpus-source.ts runs during generation, so a stubbed source
 * cannot even produce this file. The generated module then carries the same
 * positive assertions so the guard exists on the browser side too — generation
 * and rendering are different machines and both have to be honest.
 */

import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_ROOT, loadCorpus } from './corpus-source.ts';

export function buildCorpusTs(): string {
  const { manifest, files, clientOnly, digests } = loadCorpus();
  const lines: string[] = [];

  lines.push(`// GENERATED FILE — DO NOT EDIT.`);
  lines.push(`// Generated by apps/management-web/tool/generate-corpus.ts from`);
  lines.push(`// tests/fixtures/management-web/**, which is READ-ONLY to this PID.`);
  lines.push(`// Run \`pnpm run generate\`. A stale copy fails test/guard/*.test.ts.`);
  lines.push(``);
  lines.push(`export const CORPUS_CONTRACT_VERSION = ${JSON.stringify(manifest.contractVersion)};`);
  lines.push(`export const CORPUS_SURFACE = ${JSON.stringify(manifest.surface)};`);
  lines.push(`export const CORPUS_OWNER_PID = ${JSON.stringify(manifest.pid)};`);
  lines.push(``);

  lines.push(`/** Fixture bodies, keyed by manifest-relative path. */`);
  lines.push(`export const CORPUS: Readonly<Record<string, unknown>> = {`);
  for (const [path, body] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(path)}: ${JSON.stringify(body)},`);
  }
  lines.push(`};`);
  lines.push(``);

  lines.push(`/**`);
  lines.push(` * States the manifest declares with NO server response.`);
  lines.push(` *`);
  lines.push(` * These are not gaps. No server response exists while a request is in`);
  lines.push(` * flight, and client connectivity is something the server cannot know and`);
  lines.push(` * never emits. Rendering them is the client's job; inventing a fixture for`);
  lines.push(` * them would be designing rather than consuming the contract.`);
  lines.push(` */`);
  lines.push(`export const CLIENT_ONLY_STATES = [`);
  for (const e of clientOnly) {
    lines.push(`  { screen: ${JSON.stringify(e.screen)}, state: ${JSON.stringify(e.state)}, reason: ${JSON.stringify(e.reason ?? '')} },`);
  }
  lines.push(`] as const;`);
  lines.push(``);

  lines.push(`/** Manifest entries that DO have a fixture file. */`);
  lines.push(`export const CORPUS_MANIFEST = [`);
  for (const e of manifest.fixtures.filter((f) => f.file)) {
    lines.push(
      `  { file: ${JSON.stringify(e.file)}, screen: ${JSON.stringify(e.screen)}, state: ${JSON.stringify(e.state)}, schema: ${JSON.stringify(e.schema ?? '')}, httpStatus: ${JSON.stringify(e.httpStatus ?? 200)} },`,
    );
  }
  lines.push(`] as const;`);
  lines.push(``);

  lines.push(`export const CORPUS_DIGESTS: Readonly<Record<string, string>> = {`);
  for (const [file, digest] of [...digests].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(file)}: ${JSON.stringify(digest)},`);
  }
  lines.push(`};`);
  lines.push(``);

  lines.push(`/**`);
  lines.push(` * The browser-side half of the fixture-source guard.`);
  lines.push(` *`);
  lines.push(` * Generation and rendering are different machines. The node guard proves the`);
  lines.push(` * corpus on disk was genuine; this proves what reached the browser still is.`);
  lines.push(` * Absent data looks exactly like the empty state, so this must be a POSITIVE`);
  lines.push(` * assertion on authored content, never a count.`);
  lines.push(` */`);
  lines.push(`export function assertCorpusIsGenuine(): void {`);
  lines.push(`  const fail = (why: string): never => {`);
  lines.push(`    throw new Error('PEMO FIXTURE SOURCE GUARD (browser) FAILED — ' + why);`);
  lines.push(`  };`);
  lines.push(`  const s1 = CORPUS['mob-s1-safety/default.json'] as any;`);
  lines.push(`  const smoke = s1?.events?.find((e: any) => e?.reference === 'HS-2026-08-12-004417');`);
  lines.push(`  if (!smoke) fail('the authored event HS-2026-08-12-004417 is absent');`);
  lines.push(`  if (smoke.title?.['zh-Hant'] !== '單位偵測到煙霧') fail('the Traditional Chinese title is absent');`);
  lines.push(`  const s2 = CORPUS['mob-s2-overview/default.json'] as any;`);
  lines.push(`  const hub = s2?.integrationHealth?.find((f: any) => f?.key === 'twoiothub');`);
  lines.push(`  if (hub?.name !== '2IoThub') fail('the 2IoThub feed name is wrong or absent');`);
  // RE-POINTED AT UI-045, in step with the tool-side guard in corpus-source.ts.
  // GEN-043 reshaped these fixtures to ADR-019 and retired `notice.approval.steps`;
  // the evidence moved rather than disappearing. Both halves are asserted, because
  // either could be smoothed over while the other survived.
  lines.push(`  const s5cycle = CORPUS['mob-s5-notices/lifecycle.json'] as any;`);
  lines.push(`  const stuck = s5cycle?.notices?.find((n: any) => n?.lifecycleState === 'pending_approval');`);
  lines.push(`  if (!stuck) fail('the notice stuck at pending_approval is absent');`);
  lines.push(`  const s5 = CORPUS['mob-s5-notices/detail.json'] as any;`);
  lines.push(`  const granted = s5?.notice?.history?.some((h: any) => h?.disposition === 'approval_granted');`);
  lines.push(`  if (!granted) fail('the approval_granted disposition is absent from the history chain');`);
  lines.push(`  if (CORPUS_SURFACE !== 'management') fail('this is not the management corpus');`);
  lines.push(`}`);
  lines.push(``);
  return lines.join('\n');
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const body = buildCorpusTs();
  const rel = 'src/data/corpus.g.ts';
  writeFileSync(join(APP_ROOT, rel), body, 'utf8');
  console.log(`generated ${rel} (${body.split('\n').length} lines, ${body.length} bytes)`);
}
