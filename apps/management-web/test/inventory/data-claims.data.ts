/**
 * EVERY CLIENT-AUTHORED STRING, AND WHAT IT CLAIMS ABOUT THE DATA.
 *
 * Extracted after the proof tool went stale in exactly the way the claims
 * themselves had: it injected a `normal` event and a `draft` notice to force a
 * failure, and once API-020-ST added both, the injection became a no-op and the
 * tool reported the checks "not load-bearing" — a false alarm produced by a
 * hard-coded assumption about what the corpus lacks.
 *
 * A proof that hard-codes what it violates rots the moment the thing stops being
 * absent. So the violation is DERIVED from the claim: each claim knows how to
 * break itself, and adding or closing a claim updates the proof automatically.
 */

export interface AbsenceClaim {
  screen: 's1' | 's2' | 's3' | 's4' | 's5';
  state: string;
  label: string;
  /** Values the panel asserts the corpus does not contain. */
  values: string[];
  /** Everything of this kind the corpus actually contains. */
  present: (parsed: any[]) => Set<string>;
  /** Make the corpus violate this claim, so the check has something to catch. */
  inject: (dir: string, value: string, io: ClaimIO) => void;
}

export interface ClaimIO {
  read: (rel: string) => any;
  write: (rel: string, body: unknown) => void;
}

const collect = (parsed: any[], key: string): Set<string> => {
  const out = new Set<string>();
  const walk = (v: any): void => {
    if (Array.isArray(v)) return v.forEach(walk);
    if (v && typeof v === 'object') {
      if (typeof v[key] === 'string') out.add(v[key]);
      Object.values(v).forEach(walk);
    }
  };
  walk(parsed);
  return out;
};

export const severitiesIn = (p: any[]) => collect(p, 'severity');
export const communicationStatesIn = (p: any[]) => collect(p, 'communication');
export const scopeKindsIn = (p: any[]): Set<string> => {
  const out = new Set<string>();
  const walk = (v: any): void => {
    if (Array.isArray(v)) return v.forEach(walk);
    if (v && typeof v === 'object') {
      if (typeof v.kind === 'string' && typeof v.id === 'string') out.add(v.kind);
      Object.values(v).forEach(walk);
    }
  };
  walk(p);
  return out;
};
export const feedStatesIn = (p: any[]): Set<string> => {
  const out = new Set<string>();
  for (const f of p) for (const x of f?.integrationHealth ?? []) out.add(x.state);
  return out;
};
/**
 * TWO NOTICE VOCABULARIES, TWO EXTRACTORS, AND THEY MUST NOT BE MERGED.
 *
 * `NoticeRow.state` (the S2 overview's retained pre-ADR-019 shape) and
 * `StaffNoticeListItem.lifecycleState` (ADR-019) OVERLAP on `draft`, `scheduled`
 * and `withdrawn` — the contract makes lifecycle disjoint from DISPOSITION, not
 * from the retained row. So a single merged set would let a `recentNotices` row
 * satisfy an assertion about the notices list, and the assertion would pass while
 * measuring the wrong payload. Each extractor names the field it reads.
 */
export const noticeRowStatesIn = (p: any[]): Set<string> => {
  const out = new Set<string>();
  for (const f of p) for (const n of f?.recentNotices ?? []) out.add(n.state);
  return out;
};

export const noticeLifecycleStatesIn = (p: any[]): Set<string> => {
  const out = new Set<string>();
  for (const f of p) {
    for (const n of f?.notices ?? []) if (n?.lifecycleState) out.add(n.lifecycleState);
    if (f?.notice?.lifecycleState) out.add(f.notice.lifecycleState);
  }
  return out;
};

