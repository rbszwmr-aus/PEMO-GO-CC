/* ==================================================================== UI-022-ST
 * THE SWEEP — one registry, and three dispositions rather than two.
 *
 * Three instances of one class surfaced, each found by a different accident: an
 * absence claim caught by a check after a merge falsified it, a presence claim
 * caught by looking at screenshots, and a quantity caught by another session
 * asking something unrelated. None was found by a check built to find it.
 *
 * THE THIRD DISPOSITION IS THE ONE THAT HAD TO BE LEARNED.
 *
 * A claim this surface cannot in principle verify is moved to the layer that can
 * prove it, or removed. It is NEVER gated — a gate implies the surface could
 * tell. `shell.grantsNote` said "a row you should not see never arrives", which
 * is a claim about what did NOT arrive; a client sees only what did. The
 * invariant is real and GEN-018-ST asserts it server-side in the strong form
 * ADR-007 D5 requires. What stays here is a statement about the system.
 *
 * DISPOSITIONS
 *   gated       the page can tell — conditional on the data, and the gate asserted
 *   deleted     nothing renders it and nothing names the surface it belongs to
 *   retained    never renders, but the divergence register names the surface
 *   policy      about the product or the contract, not about the rows on screen
 *   value-map   rendered by keyed lookup; the lookup IS the gate, totality asserted
 *   label       names a UI element; truth cannot depend on data
 */

export type Disposition = 'gated' | 'retained' | 'policy' | 'value-map' | 'label';
export type Direction = 'absence' | 'presence' | 'quantity' | 'invariant';

/**
 * How to make a gated claim false, so its check has something to catch.
 *
 * Declared per claim rather than named in the prover. prove:absence-claims
 * rotted one merge after it was written because it hard-coded its injections;
 * deriving them fixed it, and this registry will outlive more merges than that
 * one did. A gated claim with no violator fails `every gated claim can be
 * proven to fire`.
 */
export interface Violator {
  /** A source edit that removes the gate. */
  edit?: [relativePath: string, find: string, replace: string];
  /** Or a corpus edit that falsifies the predicate. */
  corpus?: { file: string; mutate: (body: any) => void };
}

export interface StringClaim {
  /** Dotted key into MESSAGES, or a states.ts export. */
  key: string;
  disposition: Disposition;
  /** Present when the disposition is `gated`. */
  direction?: Direction;
  /** The condition under which the string may appear. */
  gate?: string;
  /** Where that gate is asserted. */
  assertedIn?: string;
  /** Required for `policy` and `retained`: why this is the right disposition. */
  why?: string;
  /** Required for `gated`: how to make it false. */
  violator?: Violator;
}

