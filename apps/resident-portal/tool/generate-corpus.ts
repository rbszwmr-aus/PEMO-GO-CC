/**
 * Embeds the resident-portal fixture corpus into a generated TS module.
 *
 * The browser cannot read tests/fixtures/**, and this app has no network client
 * — it is fixture-backed by rule (UI-007-ST generated the same way for mobile).
 * The guard in corpus-source.ts runs during generation, so a stubbed source
 * cannot even produce this file. Committed and regenerate-and-compare tested.
 */

import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_ROOT, loadCorpus } from './corpus-source.ts';

export function buildCorpusTs(): string {
  const { manifest, files, digests } = loadCorpus({ skipDigestCheck: true });
  const lines: string[] = [];
  lines.push(`// GENERATED FILE — DO NOT EDIT.`);
  lines.push(`// Generated by apps/resident-portal/tool/generate-corpus.ts from`);
  lines.push(`// tests/fixtures/resident-portal/**, which is READ-ONLY to this PID.`);
  lines.push(`// Run \`pnpm run generate\`. A stale copy fails test/guard/*.test.ts.`);
  lines.push(``);
  lines.push(`export const CORPUS_CONTRACT_VERSION = ${JSON.stringify(manifest.contractVersion)};`);
  lines.push(`export const CORPUS_SURFACE = ${JSON.stringify(manifest.surface)};`);
  lines.push(`export const CORPUS_OWNER_PID = ${JSON.stringify(manifest.pid)};`);
  lines.push(``);
  lines.push(`/** Fixture bodies, keyed by manifest-relative path. */`);
  lines.push(`export const CORPUS: Readonly<Record<string, unknown>> = {`);
  for (const [path, body] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(path)}: ${JSON.stringify(body)},`);
  }
  lines.push(`};`);
  lines.push(``);
  lines.push(`/** Manifest entries, in declaration order. */`);
  lines.push(`export const CORPUS_MANIFEST = [`);
  for (const e of manifest.fixtures) {
    lines.push(`  { file: ${JSON.stringify(e.file)}, screen: ${JSON.stringify(e.screen)}, state: ${JSON.stringify(e.state)}, schema: ${JSON.stringify(e.schema ?? '')}, operationId: ${JSON.stringify(e.operationId ?? '')}, httpStatus: ${JSON.stringify(e.httpStatus ?? 200)} },`);
  }
  lines.push(`] as const;`);
  lines.push(``);
  lines.push(`export const CORPUS_DIGESTS: Readonly<Record<string, string>> = {`);
  for (const [file, digest] of [...digests].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${JSON.stringify(file)}: ${JSON.stringify(digest)},`);
  }
  lines.push(`};`);
  lines.push(``);
  return lines.join('\n');
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const body = buildCorpusTs();
  writeFileSync(join(APP_ROOT, 'src/data/corpus.g.ts'), body, 'utf8');
  console.log(`generated src/data/corpus.g.ts (${body.split('\n').length} lines)`);
}
