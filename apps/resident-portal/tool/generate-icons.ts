/**
 * Generates the manifest of service-icon PNGs that ACTUALLY EXIST in
 * public/icons/. ServiceIcon renders an <img> only for a name in this list, so
 * no broken image ever ships and the sidebar auto-activates a mark the moment
 * its PNG is added and `pnpm run generate` is re-run.
 *
 * WHY THIS EXISTS: Ruling 1 says bundle the export PNGs, but they are not in the
 * design handoff — both design bundles ship four files and no `icons/` folder.
 * Rather than ship broken images or invent artwork (out of scope), the slot is
 * reserved and this manifest gates real rendering on real presence. See
 * public/icons/README.md and the finding in the Step 2 report.
 *
 * Committed and regenerate-and-compare tested, like the token files.
 */

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_ROOT } from './tokens-source.ts';

const ICONS_DIR = join(APP_ROOT, 'public/icons');
const OUT = join(APP_ROOT, 'src/data/icons.g.ts');

export function presentIcons(): string[] {
  if (!existsSync(ICONS_DIR)) return [];
  return readdirSync(ICONS_DIR)
    .filter((f) => f.toLowerCase().endsWith('.png'))
    .map((f) => f.replace(/\.png$/i, ''))
    .sort();
}

export function buildIconsTs(present: string[]): string {
  return (
    `// GENERATED FILE — DO NOT EDIT.\n` +
    `// Generated by apps/resident-portal/tool/generate-icons.ts from public/icons/*.png.\n` +
    `// Run \`pnpm run generate\`. A stale copy fails test/tokens/generated-not-stale.test.ts.\n` +
    `//\n` +
    `// The design handoff shipped no icons/ folder, so this is EMPTY today. Drop the\n` +
    `// export PNGs into public/icons/ and regenerate to activate the sidebar marks.\n` +
    `\n` +
    `export const PRESENT_ICONS = [\n` +
    present.map((n) => `  ${JSON.stringify(n)},`).join('\n') +
    (present.length ? '\n' : '') +
    `] as const;\n`
  );
}

const isMain =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  const body = buildIconsTs(presentIcons());
  writeFileSync(OUT, body, 'utf8');
  console.log(`generated src/data/icons.g.ts (${presentIcons().length} icons present)`);
}
