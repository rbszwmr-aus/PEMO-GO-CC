#!/usr/bin/env node
/**
 * THE ACT VOCABULARY, DERIVED FROM THE CONTRACT (GEN-047 Amendment 1, A1).
 *
 * `permitted_actions` names what a caller may do, and it names it with the
 * contract's own operationIds — never bare verbs. One vocabulary for every
 * module: the grant-admin acts and the notice acts are values of one type, so a
 * second permissions mechanism cannot grow beside the first.
 *
 * "Is an act" is DERIVED, not declared: an operation is an act iff it is a POST.
 * Every write on this surface is a POST and every POST is a write, and a rule
 * that reads the method cannot drift from the operations the way a hand-kept
 * list of "the acts" would. The generator writes the TypeScript element type and,
 * under --check, refuses if the TS file is stale OR if any `permittedActions`
 * enum in the contract disagrees with the derived set — the yaml enum is
 * hand-written (OpenAPI has no way to say "the POST operationIds"), so it is
 * VERIFIED against the derivation rather than trusted.
 *
 *   node packages/api-contracts/generate-act-operations.mjs           write
 *   node packages/api-contracts/generate-act-operations.mjs --check   verify
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(HERE, '..', '..');
const CONTRACT = path.join(HERE, 'management-web', 'openapi.yaml');
const TS_TARGET = path.join(REPO, 'modules', 'access', 'src', 'authority', 'act-operation-ids.ts');
const check = process.argv.includes('--check');

const doc = parse(readFileSync(CONTRACT, 'utf8'));
const acts = [];
for (const [route, methods] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    if (method !== 'post' || !op || typeof op !== 'object') continue;
    if (typeof op.operationId !== 'string') { console.log(`  FAIL — POST ${route} has no operationId`); process.exit(1); }
    acts.push(op.operationId);
  }
}
const routed = [...acts].sort();   // the ROUTED acts — what a contract enum may list
// ─── INTERNAL ACTS (GEN-055): declared, creditor-named, folded into the one type ──
const internal = JSON.parse(readFileSync(path.join(HERE, 'internal-acts.json'), 'utf8')).acts;
for (const a of internal) {
  if (acts.includes(a.operationId)) { console.log(`  FAIL — ${a.operationId} is routed now; remove it from internal-acts.json`); process.exit(1); }
  if (!a.routedBy) { console.log(`  FAIL — internal act ${a.operationId} names no routing PID`); process.exit(1); }
  acts.push(a.operationId);
}
acts.sort();
if (acts.length === 0) { console.log('  FAIL — derived zero acts; the generator is not seeing the contract'); process.exit(1); }

const ts = `/**
 * GENERATED by packages/api-contracts/generate-act-operations.mjs from
 * packages/api-contracts/management-web/openapi.yaml — DO NOT EDIT.
 *
 * Every act on the management surface, by its contract operationId (GEN-047
 * Amendment 1, A1). An act is a POST; the rule is read from the method, not kept
 * as a list — plus the acts internal-acts.json declares with the PID that will
 * route them (GEN-055), refused the moment they are routed. This is the element type of \`permittedActions\` everywhere it
 * appears, so a value that is not an act operationId is a TYPE ERROR rather than
 * a runtime surprise — and it is a THIRD vocabulary, disjoint from lifecycle
 * states and dispositions by construction (they are snake_case; these are the
 * contract's camelCase operationIds).
 *
 * Regenerate with \`pnpm gen:act-operations\`. \`prove.sh\` refuses a stale copy.
 */
export type ActOperationId =
${acts.map((a) => `  | '${a}'`).join('\n')};

export const ACT_OPERATION_IDS = [
${acts.map((a) => `  '${a}',`).join('\n')}
] as const satisfies readonly ActOperationId[];

export const isActOperationId = (value: string): value is ActOperationId =>
  (ACT_OPERATION_IDS as readonly string[]).includes(value);
`;

let failed = 0;
// ── the contract's own permittedActions enums must equal the derivation ────
const walk = (node, at) => {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) { node.forEach((n, i) => walk(n, `${at}[${i}]`)); return; }
  for (const [k, v] of Object.entries(node)) {
    if (k === 'permittedActions' && v && v.items && Array.isArray(v.items.enum)) {
      const declared = [...v.items.enum].sort();
      if (JSON.stringify(declared) !== JSON.stringify(routed)) {
        failed++;
        console.log(`  FAIL — ${at}.permittedActions enum disagrees with the derived act set`);
        const missing = routed.filter((a) => !declared.includes(a));
        const extra = declared.filter((a) => !routed.includes(a));
        if (missing.length) console.log(`         missing: ${missing.join(', ')}`);
        if (extra.length) console.log(`         not an act: ${extra.join(', ')}`);
      }
    }
    walk(v, `${at}.${k}`);
  }
};
walk(doc.components.schemas, 'schemas');

if (check) {
  let current = '';
  try { current = readFileSync(TS_TARGET, 'utf8'); } catch { /* absent counts as stale */ }
  if (current !== ts) { failed++; console.log(`  FAIL — ${path.relative(REPO, TS_TARGET)} is stale; run pnpm gen:act-operations`); }
  if (failed) process.exit(1);
  console.log(`  ok     act vocabulary agrees across contract and type      ${acts.length} act(s)`);
} else {
  writeFileSync(TS_TARGET, ts);
  console.log(`wrote ${path.relative(REPO, TS_TARGET)} (${acts.length} acts)`);
  if (failed) process.exit(1);
}
