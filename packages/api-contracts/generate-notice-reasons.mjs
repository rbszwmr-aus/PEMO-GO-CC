#!/usr/bin/env node
/**
 * THE NOTICE REASON-CODE VOCABULARY, ONE SOURCE (GEN-052 D3, from UI-051 G3).
 *
 * The server registry held 15 codes across four acts and the contract said
 * `reasonCode: string` — a client could not offer a select, and a code the
 * server refused was a runtime surprise. Now `notice-reasons.json` is the source:
 * this generator writes the TS consts the registry imports, and under --check
 * VERIFIES that the contract's `NoticeTransitionRequest.reasonCode` enum equals
 * the union — the yaml is hand-written (OpenAPI cannot say "the registry's
 * union"), so it is checked against the derivation rather than trusted.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(HERE, '..', '..');
const REG = JSON.parse(readFileSync(path.join(HERE, 'notice-reasons.json'), 'utf8'));
const TS = path.join(REPO, 'apps/api/src/management/notice-reason-codes.ts');
const CONTRACT = path.join(HERE, 'management-web/openapi.yaml');
const check = process.argv.includes('--check');
const acts = Object.keys(REG.acts).sort();
const union = [...new Set(acts.flatMap((a) => REG.acts[a].codes))].sort();
let ts = `/**
 * GENERATED by packages/api-contracts/generate-notice-reasons.mjs from
 * packages/api-contracts/notice-reasons.json — DO NOT EDIT. Regenerate with
 * \`pnpm gen:notice-reasons\`; prove.sh refuses a stale copy (GEN-052 D3).
 */
`;
for (const a of acts) {
  const c = REG.acts[a];
  ts += `export const ${a.toUpperCase()}_CODES = [${c.codes.map((x) => `'${x}'`).join(', ')}] as const;\n`;
  ts += `export const ${a.toUpperCase()}_REQUIRED = ${c.required};\n`;
}
ts += `\n/** The union every transition's reasonCode must belong to — the contract enum. */\nexport const NOTICE_REASON_CODE_UNION = [\n${union.map((x) => `  '${x}',`).join('\n')}\n] as const;\nexport type NoticeReasonCode = (typeof NOTICE_REASON_CODE_UNION)[number];\n`;
let failed = 0;
const doc = parse(readFileSync(CONTRACT, 'utf8'));
const declared = doc.components.schemas.NoticeTransitionRequest?.properties?.reasonCode?.enum;
if (!Array.isArray(declared) || JSON.stringify([...declared].sort()) !== JSON.stringify(union)) {
  failed++;
  console.log('  FAIL — NoticeTransitionRequest.reasonCode enum disagrees with notice-reasons.json');
  console.log(`         registry union: ${union.join(', ')}`);
  console.log(`         contract:       ${Array.isArray(declared) ? declared.join(', ') : '(no enum)'}`);
}
if (check) {
  let cur = ''; try { cur = readFileSync(TS, 'utf8'); } catch {}
  if (cur !== ts) { failed++; console.log(`  FAIL — ${path.relative(REPO, TS)} is stale; run pnpm gen:notice-reasons`); }
  if (failed) process.exit(1);
  console.log(`  ok     notice reason codes agree across registry, type and contract   ${union.length} code(s), ${acts.length} act(s)`);
} else {
  writeFileSync(TS, ts); console.log(`wrote ${path.relative(REPO, TS)}`); if (failed) process.exit(1);
}
